"""
Shared Geometry Quality, Validation, and Finishing Pipeline for Local Mesh AI.
Enforces rigorous topological integrity on raw neural 3D outputs:
- Purges NaN, Inf, and non-finite coordinate vertices.
- Detects and repairs degenerate (zero-area) faces.
- Checks edge manifoldness, watertightness, and face normal winding.
- Validates physical scale, bounding boxes, and aspect ratios.
- Resolves the "white-material problem" by detecting monochromatic flat-white
  vertex colors/textures and synthesizing subtle ambient shading.
"""

import os
import sys
import math
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple
from dataclasses import dataclass, field, asdict

import numpy as np

try:
    import trimesh
except ImportError:
    trimesh = None


@dataclass
class GeometryValidationReport:
    mesh_path: str
    is_valid: bool = True
    vertex_count: int = 0
    face_count: int = 0
    is_watertight: bool = False
    is_winding_consistent: bool = False
    has_degenerate_faces: bool = False
    degenerate_face_count: int = 0
    has_nan_or_inf: bool = False
    nan_inf_vertex_count: int = 0
    dimensions_meters: Tuple[float, float, float] = (0.0, 0.0, 0.0)
    bounding_box_volume: float = 0.0
    has_uvs: bool = False
    has_textures: bool = False
    has_vertex_colors: bool = False
    is_flat_white: bool = False
    color_variance: float = 0.0
    repair_actions_taken: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class GeometryValidator:
    """
    Validates, sanitizes, and certifies 3D meshes generated by any engine.
    """

    def __init__(self, default_max_polys: int = 150000):
        self.default_max_polys = default_max_polys

    def validate_and_repair(
        self,
        mesh_path: str,
        output_path: Optional[str] = None,
        auto_repair: bool = True,
        max_poly_budget: Optional[int] = None
    ) -> Tuple[str, GeometryValidationReport]:
        """
        Validates the mesh at mesh_path. If auto_repair is True, cleans and sanitizes
        the mesh, saving it to output_path (or overwriting mesh_path if output_path is None).
        Returns (result_mesh_path, report).
        """
        target_path = output_path or mesh_path
        report = GeometryValidationReport(mesh_path=mesh_path)

        if not os.path.exists(mesh_path) or os.path.getsize(mesh_path) == 0:
            report.is_valid = False
            report.warnings.append(f"Mesh file does not exist or is empty: {mesh_path}")
            return mesh_path, report

        if trimesh is None:
            report.warnings.append("trimesh is not installed; geometry validation skipped.")
            return mesh_path, report

        try:
            loaded = trimesh.load(mesh_path, force="mesh", process=False)
            if isinstance(loaded, trimesh.Scene):
                if len(loaded.geometry) == 0:
                    report.is_valid = False
                    report.warnings.append("Mesh scene contains no geometric primitives.")
                    return mesh_path, report
                # Concatenate geometries in scene into single Trimesh
                geoms = list(loaded.geometry.values())
                mesh = trimesh.util.concatenate(geoms)
            else:
                mesh = loaded

            # 1. Non-finite vertices inspection
            verts = np.asarray(mesh.vertices)
            non_finite_mask = ~np.isfinite(verts).all(axis=1)
            num_bad_verts = int(np.sum(non_finite_mask))
            if num_bad_verts > 0:
                report.has_nan_or_inf = True
                report.nan_inf_vertex_count = num_bad_verts
                report.warnings.append(f"Detected {num_bad_verts} non-finite (NaN or Inf) vertex coordinates.")

            # 2. Face counts & Degenerate faces inspection
            faces = np.asarray(mesh.faces)
            report.vertex_count = len(verts)
            report.face_count = len(faces)

            if len(faces) > 0 and len(verts) > 0 and not report.has_nan_or_inf:
                # Check for degenerate zero-area faces
                try:
                    areas = mesh.area_faces
                    deg_count = int(np.sum(areas <= 1e-12))
                    if deg_count > 0:
                        report.has_degenerate_faces = True
                        report.degenerate_face_count = deg_count
                        report.warnings.append(f"Detected {deg_count} degenerate (zero-area) faces.")
                except Exception:
                    pass

                # Check watertightness & winding
                try:
                    report.is_watertight = bool(mesh.is_watertight)
                    report.is_winding_consistent = bool(mesh.is_winding_consistent)
                except Exception:
                    pass

                # Dimensions & Bounding box
                bounds = mesh.extents
                report.dimensions_meters = (round(float(bounds[0]), 4), round(float(bounds[1]), 4), round(float(bounds[2]), 4))
                report.bounding_box_volume = round(float(bounds[0] * bounds[1] * bounds[2]), 6)

            # 3. White-Material & Color Inspection
            self._inspect_material_and_colors(mesh, report)

            # 4. Auto-Repair Pipeline if enabled
            if auto_repair and (report.has_nan_or_inf or report.has_degenerate_faces or report.is_flat_white or (max_poly_budget and report.face_count > max_poly_budget)):
                mesh, repairs = self._repair_mesh(mesh, report, max_poly_budget)
                report.repair_actions_taken.extend(repairs)

                # Save repaired mesh
                mesh.export(target_path)
                report.mesh_path = target_path
                report.vertex_count = len(mesh.vertices)
                report.face_count = len(mesh.faces)
                try:
                    report.is_watertight = bool(mesh.is_watertight)
                except Exception:
                    pass

            return target_path, report

        except Exception as e:
            report.is_valid = False
            report.warnings.append(f"Geometry validation exception: {str(e)}")
            return mesh_path, report

    def _inspect_material_and_colors(self, mesh: trimesh.Trimesh, report: GeometryValidationReport):
        """
        Inspects vertex colors, UVs, and material properties to detect the white-material issue.
        """
        has_vc = False
        has_tex = False
        has_uv = False

        if hasattr(mesh, "visual"):
            if hasattr(mesh.visual, "uv") and mesh.visual.uv is not None and len(mesh.visual.uv) > 0:
                has_uv = True
            mat = getattr(mesh.visual, "material", None)
            if mat is not None and getattr(mat, "baseColorTexture", None) is not None:
                has_tex = True

            # Vertex colors inspection
            if hasattr(mesh.visual, "vertex_colors") and mesh.visual.vertex_colors is not None and len(mesh.visual.vertex_colors) > 0:
                has_vc = True
                colors = np.asarray(mesh.visual.vertex_colors)
                if colors.ndim == 2 and colors.shape[1] >= 3:
                    # Normalize to 0.0 - 1.0
                    rgb = colors[:, :3].astype(np.float32)
                    if rgb.max() > 1.0:
                        rgb = rgb / 255.0

                    # Calculate color variance across RGB channels
                    variance = float(np.var(rgb))
                    report.color_variance = round(variance, 6)
                    mean_color = np.mean(rgb, axis=0)

                    # Monochromatic flat white condition:
                    # If mean is very close to 1.0 and variance is virtually 0 (< 0.0005)
                    if np.all(mean_color > 0.94) and variance < 0.001:
                        report.is_flat_white = True
                        report.warnings.append("Mesh suffers from white-material syndrome (monochromatic flat white with zero color variance).")

        report.has_uvs = has_uv
        report.has_textures = has_tex
        report.has_vertex_colors = has_vc

    def _repair_mesh(
        self,
        mesh: trimesh.Trimesh,
        report: GeometryValidationReport,
        max_poly_budget: Optional[int]
    ) -> Tuple[trimesh.Trimesh, List[str]]:
        """
        Executes non-destructive geometry healing operations.
        """
        repairs: List[str] = []

        # 1. Purge non-finite vertices
        if report.has_nan_or_inf:
            verts = np.asarray(mesh.vertices)
            finite_mask = np.isfinite(verts).all(axis=1)
            mesh.update_vertices(finite_mask)
            repairs.append("Purged non-finite NaN/Inf vertices and associated incident faces.")

        # 2. Remove degenerate faces & duplicate vertices
        try:
            mesh.remove_degenerate_faces()
            mesh.remove_duplicate_faces()
            mesh.remove_unreferenced_vertices()
            repairs.append("Cleaned degenerate zero-area faces and unreferenced vertices.")
        except Exception:
            pass

        # 3. Consistent normal winding
        try:
            trimesh.repair.fix_winding(mesh)
            trimesh.repair.fix_normals(mesh)
            repairs.append("Enforced outward-consistent face normals and vertex winding.")
        except Exception:
            pass

        # 4. Decimate if polygon budget is exceeded
        budget = max_poly_budget or self.default_max_polys
        if len(mesh.faces) > budget:
            try:
                if hasattr(mesh, "simplify_quadric_decimation"):
                    mesh = mesh.simplify_quadric_decimation(face_count=budget)
                    repairs.append(f"Decimated mesh to polygon budget ({len(mesh.faces)} faces).")
            except Exception as dec_err:
                report.warnings.append(f"Decimation notice: {dec_err}")

        # 5. Fix monochromatic flat-white material
        if report.is_flat_white:
            try:
                # Synthesize directional ambient occlusion gradient to give surface depth
                verts = np.asarray(mesh.vertices)
                z_coords = verts[:, 2]
                z_min, z_max = z_coords.min(), z_coords.max()
                z_range = max(z_max - z_min, 1e-6)
                t = (z_coords - z_min) / z_range  # 0 at bottom, 1 at top

                # Neutral warm-tinted studio shading (base 0.72 - 0.88)
                r = (0.72 + 0.16 * t) * 255
                g = (0.70 + 0.16 * t) * 255
                b = (0.68 + 0.16 * t) * 255
                alpha = np.full_like(r, 255)

                repaired_colors = np.stack([r, g, b, alpha], axis=1).astype(np.uint8)
                mesh.visual.vertex_colors = repaired_colors
                report.is_flat_white = False
                repairs.append("Repaired monochromatic white-material: synthesized depth-aware neutral studio shading.")
            except Exception as col_fix_err:
                report.warnings.append(f"Color repair notice: {col_fix_err}")

        return mesh, repairs


# Global singleton instance
geometry_validator = GeometryValidator()
